    // Método auxiliar para carregar os livros na JTable
    private void carregarLivros() {
        DefaultTableModel modelo = new DefaultTableModel(
            new Object[]{"ID", "Título", "Autor", "Estoque"}, 0
        );

        String sql = "SELECT id, titulo, autor, quantidadeEstoque FROM livro";

        try (Connection conn = conectar();
             PreparedStatement stmt = conn.prepareStatement(sql);
             ResultSet rs = stmt.executeQuery()) {

            while (rs.next()) {
                modelo.addRow(new Object[]{
                    rs.getInt("id"),
                    rs.getString("titulo"),
                    rs.getString("autor"),
                    rs.getInt("quantidadeEstoque")
                });
            }
            TabelaLivros.setModel(modelo);

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Erro ao carregar livros: " + e.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }

